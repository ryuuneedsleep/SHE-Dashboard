const now = new Date();
const daysAgo = (d: number, hoursOffset = 0): string => {
  const date = new Date(now.getTime() - d * 24 * 3600 * 1000 - hoursOffset * 3600 * 1000);
  return date.toISOString();
};

const dateOnlyDaysAgo = (d: number): string => {
  const date = new Date(now.getTime() - d * 24 * 3600 * 1000);
  return date.toISOString().split('T')[0];
};

const dateOnlyDaysAhead = (d: number): string => {
  const date = new Date(now.getTime() + d * 24 * 3600 * 1000);
  return date.toISOString().split('T')[0];
};

